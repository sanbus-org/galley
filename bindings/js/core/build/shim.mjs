#!/usr/bin/env node
/**
 * Shared procedure-shim generator for the Galley JavaScript bindings.
 *
 * Each adapter build script (`bindings/js/<runtime>/build.mjs`) imports
 * `emitJsProcedureShim` to turn the grammar's `procedures.zig` template
 * (extern hook declarations) into a dispatch shim: every hook forwards
 * through one JS callback installed via `galley_install_js_dispatch`.
 * Unregistered slots are silent no-ops. The symbol is shared across the
 * Node, Bun, and Deno adapters — one library build serves any of them.
 */

import * as fs from "node:fs";

export const INSTALL_SYMBOL = "galley_install_js_dispatch";

export function parseProcedureTemplate(templatePath) {
  let template;
  try {
    template = fs.readFileSync(templatePath, "utf-8");
  } catch (e) {
    throw new Error(`failed to read ${templatePath}: ${e.message}`);
  }
  const pattern = /pub\s+extern\s+fn\s+(\w+)\s*\((.*)\)\s*(\w+)\s*;/;
  const hooks = [];
  const passthrough = [];
  for (const line of template.split("\n")) {
    const m = pattern.exec(line.trim());
    if (m) {
      hooks.push({ name: m[1], params: m[2], ret: m[3] });
      continue;
    }
    if (
      line.trim().startsWith("pub extern") ||
      line.trim().startsWith("// Auto-generated") ||
      line.trim().startsWith("// Implement these functions")
    )
      continue;
    passthrough.push(line);
  }
  return { hooks, passthrough };
}

export function emitJsProcedureShim(templatePath, outputPath) {
  const { hooks, passthrough } = parseProcedureTemplate(templatePath);

  const builder = [];
  builder.push("// Generated by galley-js bindings; DO NOT EDIT.");
  builder.push("// Procedure hooks dispatch through a JS callback registered");
  builder.push("// by the host runtime (Node, Bun, or Deno); unregistered slots are no-ops.");
  builder.push('const std = @import("std");');
  for (const line of passthrough) builder.push(line);
  if (builder.length && builder[builder.length - 1].trim() !== "") builder.push("");
  builder.push(
    "var js_dispatch_target: ?*const fn ([*]const u8, usize, ?*anyopaque) callconv(.c) void = null;",
  );
  builder.push("");
  builder.push("fn dispatch(comptime name: []const u8, args: *root.data_structures.ProcedureArguments) void {");
  builder.push("    if (js_dispatch_target) |target| {");
  builder.push("        target(name.ptr, name.len, @ptrCast(args));");
  builder.push("    }");
  builder.push("}");
  builder.push("");
  for (const h of hooks) {
    builder.push(`pub fn ${h.name}(args: ${h.params}) ${h.ret} {`);
    builder.push(`    dispatch("${h.name}", args);`);
    builder.push("}");
    builder.push("");
  }
  builder.push(
    `export fn ${INSTALL_SYMBOL}(target: *const fn ([*]const u8, usize, ?*anyopaque) callconv(.c) void) void {`,
  );
  builder.push("    js_dispatch_target = target;");
  builder.push("}");
  builder.push("");
  fs.writeFileSync(outputPath, builder.join("\n"), "utf-8");
}

/**
 * WebAssembly procedure-shim variant for `bindings/js/wasm`.
 *
 * Same hook set as {@link emitJsProcedureShim} (parsed by the shared
 * {@link parseProcedureTemplate}), but each hook forwards through an
 * imported host function instead of an installed function pointer: wasm
 * modules cannot receive raw host addresses, so the adapter provides
 * `galley_js_dispatch` in the `env` import object at instantiation. The
 * import is unconditional — unregistered slots are no-ops in the core
 * registry, matching native semantics.
 */
export const DISPATCH_IMPORT_MODULE = "env";
export const DISPATCH_IMPORT_NAME = "galley_js_dispatch";

export function emitJsProcedureShimWasm(templatePath, outputPath) {
  const { hooks, passthrough } = parseProcedureTemplate(templatePath);
  const builder = [];
  builder.push("// Generated by galley-js bindings; DO NOT EDIT.");
  builder.push("// Procedure hooks dispatch through the host-provided");
  builder.push("// galley_js_dispatch import (see bindings/js/wasm).");
  builder.push('const std = @import("std");');
  for (const line of passthrough) builder.push(line);
  if (builder.length && builder[builder.length - 1].trim() !== "") builder.push("");
  builder.push(
    "extern fn galley_js_dispatch(name_ptr: [*]const u8, name_len: usize, args: ?*anyopaque) void;",
  );
  builder.push("");
  builder.push("fn dispatch(comptime name: []const u8, args: *root.data_structures.ProcedureArguments) void {");
  builder.push("    galley_js_dispatch(name.ptr, name.len, @ptrCast(args));");
  builder.push("}");
  builder.push("");
  for (const h of hooks) {
    builder.push(`pub fn ${h.name}(args: ${h.params}) ${h.ret} {`);
    builder.push(`    dispatch("${h.name}", args);`);
    builder.push("}");
    builder.push("");
  }
  fs.writeFileSync(outputPath, builder.join("\n"), "utf-8");
}
