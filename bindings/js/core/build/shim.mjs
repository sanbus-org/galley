#!/usr/bin/env node
/**
 * Shared procedure-shim generator for the Galley JavaScript bindings.
 *
 * Each adapter build script (`bindings/js/<runtime>/build.mjs`) imports
 * `emitJsProcedureShim` to turn the generator's `procedures` hook list
 * (metadata.json) into a dispatch shim: every hook forwards through one
 * JS callback installed via `galley_install_js_dispatch`. Unregistered
 * slots are silent no-ops. The symbol is shared across the Node, Bun, and
 * Deno adapters — one library build serves any of them. The generator owns
 * the hook list; this module renders it.
 */

import * as fs from "node:fs";

export const INSTALL_SYMBOL = "galley_install_js_dispatch";

const PREAMBLE = [
  "const std = @import(\"std\");",
  'const root = @import("galley");',
  "pub const Payload = struct {};",
  "",
];

export function readProcedureHooks(metadataPath) {
  let metadata;
  try {
    metadata = fs.readFileSync(metadataPath, "utf-8");
  } catch (e) {
    throw new Error(`failed to read ${metadataPath}: ${e.message}`);
  }
  let parsed;
  try {
    parsed = JSON.parse(metadata);
  } catch (e) {
    throw new Error(`failed to parse ${metadataPath}: ${e.message}`);
  }
  if (!parsed || !Array.isArray(parsed.procedures) || parsed.procedures.length === 0) {
    throw new Error(`${metadataPath} has no procedure hook list; update the Galley checkout`);
  }
  return parsed.procedures;
}

export function emitJsProcedureShim(metadataPath, outputPath) {
  const hooks = readProcedureHooks(metadataPath);

  const builder = [];
  builder.push("// Generated by galley-js bindings; DO NOT EDIT.");
  builder.push("// Procedure hooks dispatch through a JS callback registered");
  builder.push("// by the host runtime (Node, Bun, or Deno); unregistered slots are no-ops.");
  for (const line of PREAMBLE) builder.push(line);
  builder.push(
    "var js_dispatch_target: ?*const fn ([*]const u8, usize, ?*anyopaque) callconv(.c) void = null;",
  );
  builder.push("");
  builder.push("fn dispatch(comptime name: []const u8, args: *root.data_structures.ProcedureArguments) void {");
  builder.push("    if (js_dispatch_target) |target| {");
  builder.push("        target(name.ptr, name.len, @ptrCast(args));");
  builder.push("    }");
  builder.push("}");
  builder.push("");
  for (const name of hooks) {
    builder.push(`pub fn ${name}(args: *root.data_structures.ProcedureArguments) void {`);
    builder.push(`    dispatch("${name}", args);`);
    builder.push("}");
    builder.push("");
  }
  builder.push(
    `export fn ${INSTALL_SYMBOL}(target: *const fn ([*]const u8, usize, ?*anyopaque) callconv(.c) void) void {`,
  );
  builder.push("    js_dispatch_target = target;");
  builder.push("}");
  builder.push("");
  fs.writeFileSync(outputPath, builder.join("\n"), "utf-8");
}

/**
 * WebAssembly procedure-shim variant for `bindings/js/wasm`.
 *
 * Same hook set as {@link emitJsProcedureShim} (the generator's
 * `procedures` list), but each hook forwards through an imported host
 * function instead of an installed function pointer: wasm modules cannot
 * receive raw host addresses, so the adapter provides
 * `galley_js_dispatch` in the `env` import object at instantiation. The
 * import is unconditional — unregistered slots are no-ops in the core
 * registry, matching native semantics.
 */
export const DISPATCH_IMPORT_MODULE = "env";
export const DISPATCH_IMPORT_NAME = "galley_js_dispatch";

export function emitJsProcedureShimWasm(metadataPath, outputPath) {
  const hooks = readProcedureHooks(metadataPath);
  const builder = [];
  builder.push("// Generated by galley-js bindings; DO NOT EDIT.");
  builder.push("// Procedure hooks dispatch through the host-provided");
  builder.push("// galley_js_dispatch import (see bindings/js/wasm).");
  builder.push('const std = @import("std");');
  for (const line of PREAMBLE.slice(1)) builder.push(line);
  builder.push(
    "extern fn galley_js_dispatch(name_ptr: [*]const u8, name_len: usize, args: ?*anyopaque) void;",
  );
  builder.push("");
  builder.push("fn dispatch(comptime name: []const u8, args: *root.data_structures.ProcedureArguments) void {");
  builder.push("    galley_js_dispatch(name.ptr, name.len, @ptrCast(args));");
  builder.push("}");
  builder.push("");
  for (const name of hooks) {
    builder.push(`pub fn ${name}(args: *root.data_structures.ProcedureArguments) void {`);
    builder.push(`    dispatch("${name}", args);`);
    builder.push("}");
    builder.push("");
  }
  fs.writeFileSync(outputPath, builder.join("\n"), "utf-8");
}
