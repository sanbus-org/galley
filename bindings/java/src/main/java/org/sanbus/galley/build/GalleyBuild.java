package org.sanbus.galley.build;

import java.io.*;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.util.*;


/**
 * Builds a Galley parser and its shared library for a Java consumer.
 *
 * Usage: java -jar galley.jar &lt;language-dir&gt; [--optimize &lt;mode&gt;] [generator flags...]
 *
 * `--optimize` takes a Zig build mode (Debug, ReleaseSafe, ReleaseFast,
 * ReleaseSmall) for the parser library; without it the library builds
 * ReleaseFast. Debug builds enable the runtime's misuse checks; release
 * builds do not check.
 *
 * Generator flags forward verbatim to the generator ahead of
 * `--emit-host-procedures`: this tool forwards every flag it does not own and
 * the binary owns its surface (unknown flags die there with `unknown
 * argument`), so new generator flags work with no wrapper changes. Only
 * `--parser-type`'s value-shape is known here (`--parser-type lr` and
 * `--parser-type=lr` both forward). `--watch` is refused loudly:
 * forwarding it would park the build inside the generator's watch loop
 * and never compile.
 *
 * The language dir must contain ll.grm and may contain config.zig,
 * procedures.java (Java hooks dispatched through the generator's host
 * shim; the packaged layout <package>/procedures.java is canonical and
 * also yields the generated per-grammar Parser wiring),
 * ll_error_messages.zig, etc. A
 * procedures.c/procedures.cpp next to the grammar is a fatal build
 * error naming procedures.java as the host file to use instead.
 *
 * Environment overrides: ZIG_EXECUTABLE (default zig),
 *   GALLEY_CHECKOUT (required: existing Galley working tree).
 *
 * Generates parser (--emit-host-procedures), builds shared library through generic
 * consumer build directly next to the grammar, so the consumer can name it
 * outright via Galley.load(path). To fetch
 * a checkout for convenience, use examples/scripts/fetch-galley.sh — that
 * cache is an examples-only convenience, not part of the bindings.
 */
public final class GalleyBuild {

    private static final String LIBRARY_NAME = "galley-java";

    private static final String GENERATED_BANNER = "// Generated by galley-bindings; DO NOT EDIT.";

    private GalleyBuild() {}

    private static void fatal(String msg) {
        System.err.println("galley-bindings: " + msg);
        System.exit(1);
    }

    // Single gate for every generated write (the Parser
    // class): reads the file and reports whether it carries the generated
    // marker. Absent files read as null; unreadable files are fatal.
    // Returns null when absent, true when generated, false when foreign.
    private static Boolean isGenerated(Path path) {
        if (!Files.isRegularFile(path)) return null;
        String existing;
        try {
            existing = Files.readString(path, StandardCharsets.UTF_8);
        } catch (IOException e) {
            fatal("failed to read " + path + ": " + e.getMessage());
            return null;
        }
        return existing.startsWith(GENERATED_BANNER);
    }

    private static void assertGeneratedOrAbsent(Path path) {
        if (Boolean.FALSE.equals(isGenerated(path))) {
            fatal(path + " exists and was not generated by galley-bindings; move it aside");
        }
    }

    private static void run(List<String> cmd, Path cwd) {
        System.out.println("+ " + String.join(" ", cmd));
        try {
            ProcessBuilder pb = new ProcessBuilder(cmd);
            if (cwd != null) pb.directory(cwd.toFile());
            pb.inheritIO();
            Process p = pb.start();
            int code = p.waitFor();
            if (code != 0) fatal("command failed: " + String.join(" ", cmd) + " (exit " + code + ")");
        } catch (IOException e) {
            fatal("executable not found: " + cmd.get(0) + " (" + e.getMessage() + ")");
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            fatal("interrupted");
        }
    }

    private static String capture(List<String> cmd) {
        try {
            ProcessBuilder pb = new ProcessBuilder(cmd);
            pb.redirectErrorStream(false);
            Process p = pb.start();
            String out = new String(p.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
            String err = new String(p.getErrorStream().readAllBytes(), StandardCharsets.UTF_8);
            int code = p.waitFor();
            if (code != 0) fatal("command failed: " + String.join(" ", cmd));
            return out;
        } catch (IOException e) {
            fatal("failed to probe " + cmd.get(0) + ": " + e.getMessage());
            return "";
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            fatal("interrupted");
            return "";
        }
    }

    private static String zigExecutable() {
        String v = System.getenv("ZIG_EXECUTABLE");
        return (v != null && !v.isEmpty()) ? v : "zig";
    }

    private static Path resolveGalley() {
        String checkoutEnv = System.getenv("GALLEY_CHECKOUT");
        if (checkoutEnv == null || checkoutEnv.isEmpty()) {
            fatal("GALLEY_CHECKOUT is not set; point it at a Galley checkout (examples/scripts/fetch-galley.sh can fetch one)");
        }
        Path checkout = Paths.get(checkoutEnv);
        if (!Files.exists(checkout.resolve("build.zig"))) {
            fatal("GALLEY_CHECKOUT=" + checkout + " is not a Galley repository checkout (no build.zig)");
        }
        return checkout.toAbsolutePath();
    }

    private static String libFileName(String base) {
        String os = System.getProperty("os.name", "").toLowerCase();
        if (os.contains("mac")) return "lib" + base + ".dylib";
        if (os.contains("win")) return base + ".dll";
        return "lib" + base + ".so";
    }

    private static Path findJavaProceduresFile(Path languageDir) {
        Path candidate = languageDir.resolve("procedures.java");
        if (Files.isRegularFile(candidate)) return candidate;
        return null;
    }

    // Java package spelling of the language directory name. The generated
    // per-grammar Parser lives in this package next to the hook source, so
    // it names the hook class without an import.
    private static String packageNameFor(Path languageDir) {
        String raw = languageDir.getFileName().toString();
        StringBuilder cleaned = new StringBuilder(raw.length());
        for (int i = 0; i < raw.length(); i++) {
            char ch = raw.charAt(i);
            cleaned.append(Character.isLetterOrDigit(ch) || ch == '_' ? ch : '_');
        }
        if (cleaned.length() == 0) fatal(languageDir + " cannot spell a Java package; rename the directory");
        if (Character.isDigit(cleaned.charAt(0))) cleaned.insert(0, '_');
        return cleaned.toString();
    }

    private static Path findPackagedJavaProceduresFile(Path languageDir, String packageName) {
        Path candidate = languageDir.resolve(packageName).resolve("procedures.java");
        if (Files.isRegularFile(candidate)) return candidate;
        return null;
    }

    // Removes a stale banner-carrying Parser left by an earlier packaged
    // build. Foreign (hand-written) files are never touched.
    private static void deleteIfGenerated(Path path) {
        if (!Boolean.TRUE.equals(isGenerated(path))) return;
        System.err.println("galley-bindings: removing stale generated " + path);
        try {
            Files.delete(path);
        } catch (IOException e) {
            fatal("failed to remove stale " + path + ": " + e.getMessage());
        }
    }

    // Per-grammar Parser class: banner-guarded, fixed class name. load()
    // installs every hook the procedures class defines through
    // installProcedures(<class>.class), which scans its methods with the
    // rule Python and JavaScript package scans use, so the class defines
    // only the hooks it implements. One package is one parser per process: load() memoizes
    // it and wires the bundled hooks exactly once, storing the parser only
    // after the install succeeded, so a failed first load caches nothing
    // and a retry is a fresh attempt. Bare Galley.load wires nothing, and
    // later installs win per hook name. Refuses to overwrite a file it did
    // not generate.
    private static void emitParserClass(String packageName, String hookClass, Path languageDir) {
        Path packageDir = languageDir.resolve(packageName);
        Path outputPath = packageDir.resolve("Parser.java");
        assertGeneratedOrAbsent(outputPath);
        List<String> lines = new ArrayList<>();
        lines.add(GENERATED_BANNER);
        lines.add("// Bundled hook wiring for this grammar: every hook " + hookClass + " defines.");
        lines.add("// One parser per process for this package: load() wires the bundled hooks");
        lines.add("// exactly once, and later installs win per hook name.");
        lines.add("package " + packageName + ";");
        lines.add("");
        lines.add("public final class Parser {");
        lines.add("");
        lines.add("    private Parser() {}");
        lines.add("");
        lines.add("    private static org.sanbus.galley.Parser parser;");
        lines.add("");
        lines.add("    public static synchronized org.sanbus.galley.Parser load(String libraryPath) throws org.sanbus.galley.MissingArtifactException {");
        lines.add("        if (parser == null) {");
        lines.add("            org.sanbus.galley.Parser loaded = org.sanbus.galley.Galley.load(libraryPath);");
        lines.add("            loaded.installProcedures(" + hookClass + ".class);");
        lines.add("            parser = loaded;");
        lines.add("        }");
        lines.add("        return parser;");
        lines.add("    }");
        lines.add("}");
        try {
            Files.createDirectories(packageDir);
            Files.writeString(outputPath, String.join("\n", lines) + "\n", StandardCharsets.UTF_8);
        } catch (IOException e) {
            fatal("failed to write parser: " + e.getMessage());
        }
    }

    // The --parser-type selection inside forwarded generator flags, if
    // any. Last wins on both spellings (--parser-type lr,
    // --parser-type=lr), mirroring the binary. Anything else (including a
    // bad value) is the generator's to reject — this only answers "must
    // ll.grm exist?". --parser-type is the one piece of generator surface
    // this tool knows: its value-shape is needed to find the grammar
    // file. Every other flag forwards untouched and the binary owns it.
    private static String parserTypeFromFlags(List<String> flags) {
        String parserType = null;
        for (int i = 0; i < flags.size(); i++) {
            String flag = flags.get(i);
            if (flag.equals("--parser-type")) {
                i++;
                parserType = (i < flags.size()) ? flags.get(i) : null;
            } else if (flag.startsWith("--parser-type=")) {
                parserType = flag.substring("--parser-type=".length());
            }
        }
        return parserType;
    }

    // The consumer build command for the parser library. -Doptimize appears
    // only when the user chose a mode; the consumer build owns the default.
    private static List<String> consumerBuildArguments(
            Path consumerBuildFile, Path languageDir, String proceduresZigSource, String optimize) {
        List<String> arguments = new ArrayList<>(Arrays.asList(
                zigExecutable(), "build",
                "--build-file", consumerBuildFile.toString(),
                "-Dlanguage-dir=" + languageDir.toString(),
                "-Dlib-name=" + LIBRARY_NAME,
                "-Doutput=" + libFileName(LIBRARY_NAME)
        ));
        if (optimize != null && !optimize.isEmpty()) arguments.add("-Doptimize=" + optimize);
        // config.zig and {ll,lr}_error_messages.zig are inferred by the
        // consumer build from the parser location.
        arguments.add("-Dprocedures-zig-source=" + proceduresZigSource);
        arguments.addAll(Arrays.asList("--prefix", languageDir.toString(), "install"));
        return arguments;
    }

    public static void main(String[] args) {
        String usage = "usage: galley-java <language-dir> [--optimize <mode>] [generator flags...]";
        if (args.length < 1) fatal(usage);
        String os = System.getProperty("os.name", "").toLowerCase();
        if (os.contains("win")) fatal("the java bindings target POSIX platforms");
        Path languageDir = Paths.get(args[0]).toAbsolutePath().normalize();
        List<String> generatorFlags = new ArrayList<>();
        String optimize = null;
        for (int i = 1; i < args.length; i++) {
            String flag = args[i];
            if (flag.equals("-h") || flag.equals("--help")) {
                System.out.println(usage);
                return;
            }
            if (flag.equals("--watch")) fatal("--watch needs its own entry (not yet implemented); this build runs the generator once");
            if (flag.equals("--optimize")) {
                i++;
                if (i >= args.length) fatal("--optimize needs Debug, ReleaseSafe, ReleaseFast or ReleaseSmall; " + usage);
                optimize = args[i];
            } else if (flag.equals("--parser-type")) {
                i++;
                if (i >= args.length) fatal("--parser-type needs ll or lr; " + usage);
                generatorFlags.add(flag);
                generatorFlags.add(args[i]);
            } else if (flag.startsWith("-")) {
                generatorFlags.add(flag);
            } else {
                fatal("unexpected positional argument " + flag + "; " + usage);
            }
        }
        // Single-parser generation needs only its own grammar:
        // --parser-type lr runs against lr.grm alone. Anything else
        // (including a bad value) is the generator's to reject.
        if (!"lr".equals(parserTypeFromFlags(generatorFlags)) && !Files.isRegularFile(languageDir.resolve("ll.grm")))
            fatal(languageDir + " does not contain ll.grm");
        if (Files.isRegularFile(languageDir.resolve("procedures.c")) || Files.isRegularFile(languageDir.resolve("procedures.cpp")))
            fatal("procedures.c/procedures.cpp is not a Java hook source: implement hooks in procedures.java");

        String packageName = packageNameFor(languageDir);
        Path packagedJavaProceduresFile = findPackagedJavaProceduresFile(languageDir, packageName);
        Path javaProceduresFile = findJavaProceduresFile(languageDir);
        if (packagedJavaProceduresFile != null) {
            if (javaProceduresFile != null) System.err.println("galley-bindings: both packaged (" + packagedJavaProceduresFile + ") and top-level (" + javaProceduresFile + ") Java procedures found — using packaged");
            javaProceduresFile = packagedJavaProceduresFile;
        }
        // Check every clobber guard before generating anything: a
        // hand-written file in a generated path survives a rebuild
        // instead of being half-overwritten.
        Path packagedParserPath = languageDir.resolve(packageName).resolve("Parser.java");
        if (packagedJavaProceduresFile != null) {
            assertGeneratedOrAbsent(packagedParserPath);
        } else {
            deleteIfGenerated(packagedParserPath);
        }

        Path galleySource = resolveGalley();
        Path cli = galleySource.resolve("zig-out").resolve("bin").resolve("galley");
        if (!Files.exists(cli)) {
            run(Arrays.asList(zigExecutable(), "build", "-Doptimize=ReleaseFast", "install"), galleySource);
        }

        String help = capture(Arrays.asList(cli.toString(), "--help"));
        if (!help.contains("--emit-host-procedures")) {
            fatal("the Galley at " + galleySource + " is too old for the bindings workflow (no --emit-host-procedures support); update the checkout");
        }

        List<String> generateArgs = new ArrayList<>();
        generateArgs.add(cli.toString());
        generateArgs.addAll(generatorFlags);
        generateArgs.add("--emit-host-procedures");
        generateArgs.add(languageDir.toString());
        run(generateArgs, null);

        if (javaProceduresFile != null) {
            System.err.println("galley-bindings: using Java procedures from " + javaProceduresFile);
        }
        // Every build links the generator's host shim: the library then
        // forwards every hook its parser binds, none when the grammar
        // disables procedures, in which case installing one raises.
        String proceduresZigSource = languageDir.resolve("host_procedures.zig").toString();

        // One library embeds one parser; the consumer build locates the file
        // generation produced from -Dlanguage-dir and infers the family
        // from the filename.
        List<String> consumerArgs = consumerBuildArguments(
                galleySource.resolve("bindings").resolve("c").resolve("consumer").resolve("build.zig"),
                languageDir, proceduresZigSource, optimize);
        run(consumerArgs, galleySource);

        Path dest = languageDir.resolve(libFileName(LIBRARY_NAME));
        if (!Files.exists(dest)) fatal("expected library not found at " + dest);

        if (packagedJavaProceduresFile != null) {
            String hookClass = packagedJavaProceduresFile.getFileName().toString();
            hookClass = hookClass.substring(0, hookClass.length() - ".java".length());
            emitParserClass(packageName, hookClass, languageDir);
        }

        System.out.println("galley-bindings: built " + dest + "; import from " + languageDir);
    }
}
