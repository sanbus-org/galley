const std = @import("std");
const common = @import("build/common.zig");

pub fn build(b: *std.Build) !void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});

    const generator = common.addGeneratorModules(b, target, optimize);
    const galley_cli = common.addGalleyCli(b, target, optimize, generator, .{
        .install_default = true,
        .add_galley_step = true,
    });
    const standalone_scaffold_step = addStandaloneScaffoldTest(b, galley_cli.generator_cli_exe);

    const package_consumer_step = b.step(
        "test-package-consumer",
        "Build and run an external project using galley_generator",
    );
    const package_consumer = b.addSystemCommand(&.{
        b.graph.zig_exe,
        "build",
        "--build-file",
        b.pathFromRoot("tests/package-consumer/build.zig"),
    });
    if (b.graph.max_jobs) |max_jobs| {
        package_consumer.addArg(b.fmt("-j{d}", .{max_jobs}));
    }
    package_consumer_step.dependOn(&package_consumer.step);

    const test_filters = b.option([]const []const u8, "test-filter", "Select tests by suite:, case:, and name:") orelse &.{};
    const test_step = common.addDelegatedTestStep(b, "test", "Run all tests (build + generator + runtime + matrix + parity)", "test", test_filters, generator.ast_memory_benchmark);
    if (test_filters.len == 0) test_step.dependOn(standalone_scaffold_step);
    _ = common.addDelegatedTestStep(
        b,
        "test-generated-parser-matrix",
        "Generate and test parser option matrix",
        "test-generated-parser-matrix",
        test_filters,
        generator.ast_memory_benchmark,
    );
    _ = common.addDelegatedTestStep(
        b,
        "test-galley-bootstrap-parity",
        "Compare parser output generated by ll-galley and lr-galley",
        "test-galley-bootstrap-parity",
        test_filters,
        generator.ast_memory_benchmark,
    );
    _ = common.addDelegatedTestStep(
        b,
        "test-benchmark-progress",
        "Run benchmark progress planning and terminal rendering tests",
        "test-benchmark-progress",
        &.{},
        generator.ast_memory_benchmark,
    );
    _ = common.addDelegatedTestStep(
        b,
        "compare-galley-recovery",
        "Show automatic and explicit recovery on the same malformed Galley grammar",
        "compare-galley-recovery",
        &.{},
        generator.ast_memory_benchmark,
    );

    var dir = try b.build_root.handle.openDir(b.graph.io, common.languages_path, .{ .iterate = true });
    defer dir.close(b.graph.io);

    var walker = try dir.walk(b.allocator);
    defer walker.deinit();
    while (try walker.next(b.graph.io)) |entry| {
        if (entry.kind != .directory and entry.kind != .sym_link) continue;

        inline for ([_][]const u8{ "ll", "lr" }) |parser_type| {
            if (try common.addLanguageParser(
                b,
                target,
                optimize,
                generator,
                entry.path,
                parser_type,
            )) |parser| {
                try common.addApiBenchmark(b, target, optimize, parser);
            }
        }
    }
}

fn addStandaloneScaffoldTest(
    b: *std.Build,
    generator_cli: *std.Build.Step.Compile,
) *std.Build.Step {
    const step = b.step(
        "test-standalone-scaffold",
        "Scaffold, build, and test an external standalone parser project",
    );

    const files = b.addWriteFiles();
    files.mode = .tmp;
    const grammar =
        \\Start
        \\| "a"
        \\
    ;
    _ = files.add("ll.grm", grammar);
    _ = files.add("lr.grm", grammar);
    _ = files.add("samples/code-01", "a");
    // This deliberately invalid sample catches regressions where the generated
    // executable scans samples/code-* instead of parsing its requested input.
    _ = files.add("samples/code-02", "b");
    const project_dir = files.getDirectory();

    const scaffold = b.addRunArtifact(generator_cli);
    scaffold.setName("scaffold standalone parser project");
    scaffold.has_side_effects = true;
    scaffold.addDirectoryArg(project_dir);

    const build_scaffold = b.addSystemCommand(&.{
        b.graph.zig_exe,
        "build",
        "--build-file",
    });
    build_scaffold.setName("build and test standalone parser project");
    build_scaffold.addFileArg(project_dir.path(b, "build.zig"));
    build_scaffold.addArgs(&.{ "ll", "lr", "test" });
    if (b.graph.max_jobs) |max_jobs| {
        build_scaffold.addArg(b.fmt("-j{d}", .{max_jobs}));
    }
    build_scaffold.step.dependOn(&scaffold.step);

    const run_ll_file = b.addSystemCommand(&.{
        b.graph.zig_exe,
        "build",
        "--build-file",
    });
    run_ll_file.setName("run standalone LL parser with file input");
    run_ll_file.addFileArg(project_dir.path(b, "build.zig"));
    run_ll_file.addArgs(&.{ "run-ll", "--" });
    run_ll_file.addFileArg(project_dir.path(b, "samples/code-01"));
    run_ll_file.step.dependOn(&build_scaffold.step);

    const run_lr_stdin = b.addSystemCommand(&.{
        b.graph.zig_exe,
        "build",
        "--build-file",
    });
    run_lr_stdin.setName("run standalone LR parser with stdin input");
    run_lr_stdin.addFileArg(project_dir.path(b, "build.zig"));
    run_lr_stdin.addArg("run-lr");
    run_lr_stdin.setStdIn(.{ .bytes = "a" });
    run_lr_stdin.step.dependOn(&run_ll_file.step);

    step.dependOn(&run_lr_stdin.step);
    return step;
}
